"""Generate or check policy.json from the installed Battlecode engine package.

The bot policy is the engine's own policy (docs/CHANGE_NOTICES.md CN-004): the imports its runner
allows and the builtins and globals its runner gives to a bot. This script reads them from the
engine so they cannot drift unnoticed.

    backend/.venvs/py3.15/bin/python backend/bot_validator/generate_policy.py --write
    backend/.venvs/py3.15/bin/python backend/bot_validator/generate_policy.py --check   # exit 1 on drift
"""
from __future__ import annotations

import builtins
import json
import sys
import types
from pathlib import Path

HERE = Path(__file__).resolve().parent
POLICY_PATH = HERE / "policy.json"
ENGINE_IMPORT_PROBE = ["random", "math", "enum", "battlecode26", "os", "sys", "time", "json", "re", "collections"]

# Not part of the engine's policy: names the validator reports as warnings because the engine
# allows them but they matter for isolation (see docs/BOT_POLICY.md).
RISKY_NAMES = ["open", "setattr", "delattr", "__import__"]
RISKY_ATTRIBUTES = ["__class__", "__base__", "__bases__", "__mro__", "__subclasses__", "__globals__",
                    "__code__", "__builtins__", "__dict__", "__closure__", "__getattribute__",
                    "__import__", "__loader__", "__reduce__", "__reduce_ex__"]


def read_engine() -> dict:
    sys.path.insert(0, str(HERE.parent.parent))
    from backend.match_runner import runner_entry

    runner_entry.import_engine()
    import battlecode26
    from battlecode26.runner import RobotRunner
    from battlecode26.wrappers import _GAME_METHODS

    r = RobotRunner(code={"bot": ""}, game_methods=_GAME_METHODS, error_method=print, bytecode_limit=10**9)
    try:
        table = r.globals["__builtins__"]
        std = set(vars(builtins))
        allowed_builtins = sorted(k for k in table if k in std and not k.startswith("_"))
        engine_globals = sorted(k for k in table if k not in std and not k.startswith("_"))
        imports_ok = []
        for name in ENGINE_IMPORT_PROBE:
            try:
                r.import_call(name)
                imports_ok.append(name)
            except ImportError:
                pass
        exports = sorted(n for n in vars(battlecode26)
                         if not n.startswith("_") and not isinstance(vars(battlecode26)[n], types.ModuleType))
        pkg_version = __import__("importlib.metadata", fromlist=["version"]).version("battlecode26")
    finally:
        r.kill()
    return {
        "_comment": "Generated by generate_policy.py from the installed engine. Do not edit by hand.",
        "engine_package": {"name": "battlecode26", "metadata_version": pkg_version},
        "bot_file": "bot.py",
        "entry_point": "turn",
        "allowed_imports": sorted(imports_ok),
        "allowed_builtins": allowed_builtins,
        "engine_globals": engine_globals,
        "battlecode26_exports": exports,
        "allowed_dunder_names": ["__name__", "__import__"],
        "risky_names": RISKY_NAMES,
        "risky_attributes": RISKY_ATTRIBUTES,
        "max_bytes": None,
    }


def main(argv: list[str]) -> int:
    fresh = read_engine()
    if "--write" in argv:
        old = json.loads(POLICY_PATH.read_text()) if POLICY_PATH.exists() else {}
        fresh["max_bytes"] = old.get("max_bytes")  # an owner decision, never generated
        POLICY_PATH.write_text(json.dumps(fresh, indent=2) + "\n")
        print(f"wrote {POLICY_PATH}")
        return 0
    current = json.loads(POLICY_PATH.read_text())
    keys = ["engine_package", "allowed_imports", "allowed_builtins", "engine_globals", "battlecode26_exports"]
    drift = {k: {"policy": current.get(k), "engine": fresh[k]} for k in keys if current.get(k) != fresh[k]}
    print(json.dumps({"ok": not drift, "drift": drift}, indent=2))
    return 0 if not drift else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
